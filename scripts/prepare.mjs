// Gets the UI ready for a build: copies the animation library, packs the icons used by the UI and stamps the version.
// node scripts/prepare.mjs [version]
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

mkdirSync('ui/vendor', { recursive: true });
copyFileSync('node_modules/motion/dist/motion.js', 'ui/vendor/motion.js');

// icons: find every ic('name') and data-i="name" in the UI, take them from Phosphor in 4 weights
const names = new Set(['x', 'check', 'copy', 'floppy-disk', 'text-t', 'sparkle', 'circle-notch', 'info', 'warning']);
for (const f of readdirSync('ui')) {
  if (!/\.(js|html)$/.test(f) || f === 'icons.js') continue;
  const s = readFileSync('ui/' + f, 'utf8');
  for (const m of s.matchAll(/\bic\('([a-z0-9-]+)'/g)) names.add(m[1]);
  for (const m of s.matchAll(/data-i="([a-z0-9-]+)"/g)) names.add(m[1]);
  for (const m of s.matchAll(/\bi:\s*'([a-z0-9-]+)'/g)) names.add(m[1]);
}
const base = 'node_modules/@phosphor-icons/core/assets';
const PH = {};
const miss = [];
for (const w of ['light', 'regular', 'bold', 'fill']) {
  PH[w] = {};
  for (const n of names) {
    const p = `${base}/${w}/${n}${w === 'regular' ? '' : '-' + w}.svg`;
    if (!existsSync(p)) { if (w === 'regular') miss.push(n); continue; }
    let svg = readFileSync(p, 'utf8').replace(/<\?xml[^>]*>/, '').replace(/\s+/g, ' ').trim();
    const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '').replace(/<rect width="256" height="256" fill="none"\s*\/>/g, '');
    PH[w][n] = `<svg class="ph" viewBox="0 0 256 256" fill="currentColor" aria-hidden="true">${inner}</svg>`;
  }
}
if (miss.length) console.log('WARNING missing icons:', miss.join(', '));
writeFileSync('ui/icons.js', '// generated by scripts/prepare.mjs from @phosphor-icons/core\nwindow.PH=' + JSON.stringify(PH) + ';\n');
console.log('icons', names.size, 'x 4 weights');

const ver = process.argv[2];
if (ver) {
  const p = 'src-tauri/tauri.conf.json';
  const c = JSON.parse(readFileSync(p, 'utf8'));
  c.version = ver;
  writeFileSync(p, JSON.stringify(c, null, 2) + '\n');
  const t = 'src-tauri/Cargo.toml';
  writeFileSync(t, readFileSync(t, 'utf8').replace(/^version = ".*"/m, `version = "${ver}"`));
}
console.log('ui ready', ver || '');
